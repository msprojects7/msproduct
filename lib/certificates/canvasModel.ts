export interface CanvasElement {
  id: string;
  type:
  | 'title'
  | 'recipient'
  | 'body'
  | 'event_name'
  | 'org_name'
  | 'signatory'
  | 'logo'
  | 'seal'
  | 'qr'
  | 'shape'
  | 'line'
  | 'text'
  | 'image';
  x: number; // percentage (0 to 100)
  y: number; // percentage (0 to 100)
  width: number; // percentage (0 to 100)
  height: number; // percentage (0 to 100)
  rotation: number; // degrees (0 to 360)
  opacity: number; // 0 to 1
  zIndex: number;
  locked?: boolean;
  hidden?: boolean;

  // Text specific
  content?: string;
  fontFamily?: 'serif' | 'sans' | 'mono' | 'display' | 'script' | 'playfair' | 'cormorant' | 'times_new_roman' | 'montserrat' | 'poppins' | 'outfit' | 'space_grotesk' | 'plus_jakarta' | 'jetbrains_mono' | string;
  fontSize?: number; // relative size in pt/px
  fontWeight?: 'normal' | 'medium' | 'semibold' | 'bold' | 'extrabold';
  fontStyle?: 'normal' | 'italic';
  color?: string;
  textAlign?: 'left' | 'center' | 'right';
  letterSpacing?: number;
  lineHeight?: number;

  // Signatory specific
  signatoryName?: string;
  signatoryTitle?: string;
  signatureUrl?: string;
  showSignatureLine?: boolean;

  // Seal specific
  sealType?: 'gold_crest' | 'laurel_wreath' | 'shield_check' | 'star_ribbon' | 'wax_seal' | 'none';
  sealColor?: string;

  // Shape/Border specific
  fillColor?: string;
  borderColor?: string;
  borderWidth?: number;
  borderStyle?: 'solid' | 'dashed' | 'double' | 'none';
  borderRadius?: number;

  // Image/Logo specific
  src?: string;
  alt?: string;
}

export interface CertificateCanvasModel {
  format: 'a4_landscape' | 'a4_portrait' | 'letter_landscape' | 'letter_portrait';
  aspectRatio: number; // width / height
  background: {
    type: 'solid' | 'gradient' | 'parchment' | 'dark' | 'image' | 'mesh';
    color: string;
    gradient?: string;
    imageUrl?: string;
    opacity?: number;
  };
  border: {
    enabled: boolean;
    style:
    | 'double_gold'
    | 'geometric'
    | 'ornate'
    | 'minimal'
    | 'dark_foil'
    | 'clean_boxed'
    | 'modern_line'
    | 'vintage'
    | 'curvy_rounded'
    | 'dashed_frame'
    | 'none';
    color: string;
    width: number;
    inset: number;
    borderRadius?: number;
  };
  elements: CanvasElement[];
}

